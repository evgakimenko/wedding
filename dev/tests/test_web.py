def new_page(b, dark=False):
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, color_scheme="dark" if dark else "light", accept_downloads=True)
    pg = ctx.new_page()
    def onc(m):
        if m.type == "error" and not re.search(r"realtime|websocket|fonts\.g|ERR_FAILED|ERR_INTERNET_DISCONNECTED|Failed to load resource", m.text, re.I): errors.append("console: " + m.text)
    pg.on("console", onc)
    pg.on("pageerror", lambda e: errors.append("pageerror: " + str(e)))
    pg.route(re.compile(r"fonts\.(googleapis|gstatic)\.com"), lambda r: r.abort())
    return ctx, pg

sheet = lambda pg: pg.locator(".sheet").last
def fill(pg, vals, root=None):
    s = root or sheet(pg)
    for k, v in vals.items():
        el = s.locator(f'[name="{k}"]')
        tag = el.evaluate("e => e.tagName")
        if tag == "SELECT": el.select_option(str(v))
        elif el.get_attribute("type") == "checkbox": el.set_checked(bool(v))
        else: el.fill(str(v))
def save(pg): sheet(pg).locator("[data-save]").click(); pg.wait_for_timeout(300)
def S(pg, expr): return pg.evaluate("() => " + expr)
def synced(pg):  # wait until outbox flushed
    pg.wait_for_function("() => outbox.length === 0", timeout=10000)

