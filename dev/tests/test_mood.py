import sys, re, io, pathlib, urllib.request, openpyxl
from playwright.sync_api import sync_playwright

BASE = "http://localhost:8000/"
ROOT = pathlib.Path(__file__).parent
SHOTS = ROOT / "shots_mood"; SHOTS.mkdir(exist_ok=True)
errors = []
def check(c, m):
    print(("  ✓ " if c else "  ✗ ") + m)
    if not c: errors.append(m)
urllib.request.urlopen(BASE + "__reset").read()

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, has_touch=True, accept_downloads=True, permissions=["clipboard-read", "clipboard-write"])
    pg = ctx.new_page()
    pg.on("console", lambda m: m.type == "error" and not re.search(r"realtime|websocket|fonts|Failed to load resource", m.text, re.I) and errors.append("console: " + m.text))
    pg.on("pageerror", lambda e: errors.append("pageerror: " + str(e)))
    pg.route(re.compile(r"fonts\.(googleapis|gstatic)\.com"), lambda r: r.abort())
    S = lambda e: pg.evaluate("() => " + e)
    sheet = lambda: pg.locator(".sheet").last
    def synced(): pg.wait_for_function("() => outbox.length === 0", timeout=10000)
    clip = lambda: pg.evaluate("() => navigator.clipboard.readText()")

    pg.goto(BASE); pg.wait_for_selector(".auth", timeout=15000)
    pg.click("[data-sw]"); pg.fill("#em", "mood@test.ru"); pg.fill("#pw", "secret12"); pg.click('.auth [type="submit"]')
    pg.wait_for_selector(".join", timeout=10000); pg.click('[data-new="p2"]'); pg.wait_for_selector(".ob", timeout=10000)
    pg.locator("[data-restore]").set_input_files(str(ROOT.parent / "migration.json")); pg.wait_for_selector(".hero", timeout=15000)

    print("\n== Атмосфера (мудборд) ==")
    pg.click('[data-go="more"]'); pg.wait_for_timeout(150)
    check(pg.locator('#app [data-go="mood"]').is_visible() and pg.locator('#app [data-go="schedule"]').is_visible(), "в «Ещё» есть «Атмосфера» и «Расписание»")
    pg.click('#app [data-go="mood"]'); pg.wait_for_timeout(200)
    check(pg.locator(".mbcard").count() == 7, "7 досок: декор, фото, видео, торт, полиграфия, идеи, ведущий")
    pg.click('[data-go="mood-decor"]'); pg.wait_for_timeout(200)
    check("Декор и флористика" in pg.locator("h1.ttl").inner_text(), "открывается доска «Декор и флористика»")
    pg.locator('[data-mbfile="decor"]').set_input_files([str(ROOT / "mood0.jpg"), str(ROOT / "mood1.jpg"), str(ROOT / "mood2.jpg")])
    pg.wait_for_function("() => S.mbphotos.length === 3", timeout=15000); pg.wait_for_timeout(500); synced()
    check(pg.locator(".mbph img").count() == 3, "загружено 3 фото, превью видны")
    sizes = pg.evaluate("async () => { const r = await sb.from('docs').select('coll,data').eq('wedding_id', W).in('coll', ['mbthumb','mbimg']); return r.data.map(x => [x.coll, x.data.img.length]); }")
    th = [s for c, s in sizes if c == "mbthumb"]; fu = [s for c, s in sizes if c == "mbimg"]
    check(len(th) == 3 and len(fu) == 3 and max(th) < 60000 and max(fu) < 500000, f"превью и полные фото сжаты (превью до {max(th)//1000} КБ)")
    check(not S("JSON.stringify(S).includes('base64')"), "картинки не грузятся в общий список данных")
    pg.locator(".mbph").first.click(); pg.wait_for_selector(".mbfull img", timeout=5000)
    sheet().locator('[name="cap"]').fill("Пионы и зелень"); sheet().locator("[data-save]").click(); pg.wait_for_timeout(300)
    check("Пионы и зелень" in pg.locator(".mbphotos").inner_text(), "подпись к фото")
    pg.locator(".mbph").nth(1).click(); pg.wait_for_timeout(200); sheet().locator("[data-del]").click(); pg.locator(".modal [data-y]").click(); pg.wait_for_timeout(500)
    check(S("S.mbphotos.length") == 2, "удаление фото")
    pg.click('[data-mblink="decor"]'); sheet().locator('[name="url"]').fill("https://pinterest.com/pin/12345"); sheet().locator('[name="caption"]').fill("арка из сухоцветов"); sheet().locator("[data-save]").click(); pg.wait_for_timeout(300)
    check("pinterest.com" in pg.locator(".mbphotos").inner_text(), "ссылка-референс (Pinterest)")
    # comments
    f = pg.locator("[data-cmform]")
    f.locator('[name="text"]').fill("Хотим больше зелени, без роз"); f.locator('button[type="submit"]').click(); pg.wait_for_timeout(250)
    pg.locator('[data-cmtype="question"]').click(); pg.locator('[data-cmform] [name="text"]').fill("Сколько стоит арка?"); pg.locator('[data-cmform] button[type="submit"]').click(); pg.wait_for_timeout(250)
    pg.locator('[data-cmtype="question"]').click(); pg.locator('[data-cmform] [name="text"]').fill("Успеете смонтировать до 14:00?"); pg.locator('[data-cmform] button[type="submit"]').click(); pg.wait_for_timeout(250)
    cm = S("S.mbcomments.map(c => c.type + ':' + c.text + ':' + c.by)")
    check(len(cm) == 3 and cm[0].startswith("wish:") and "question:Сколько стоит арка?:p2" in cm, "пожелание и вопросы сохранены с автором (Катя)")
    pg.locator("[data-cmres]").first.click(); pg.wait_for_timeout(200)
    check(S("S.mbcomments.filter(c => c.resolved).length") == 1, "вопрос отмечен «решено»")
    pg.click('[data-mbcopy="decor"]'); pg.wait_for_timeout(300)
    t = clip()
    check("Хотим больше зелени" in t and "Успеете смонтировать" in t and "Сколько стоит арка" not in t and "pinterest.com" in t and "Женя и Катя" in t, "«Скопировать для подрядчика»: пожелания, открытые вопросы, ссылки")
    pg.screenshot(path=str(SHOTS / "01_board.png"), full_page=True)
    synced()
    pg.click('h1.ttl [data-go="mood"]'); pg.wait_for_timeout(500)
    check(pg.locator(".mbcard").first.locator("img").count() == 2 and "1 вопрос" in pg.locator(".mbcard").first.inner_text(), "на обложке доски превью и счётчик открытых вопросов")
    pg.screenshot(path=str(SHOTS / "02_mood.png"), full_page=True)
    # second device sees thumbs
    ctx2 = b.new_context(viewport={"width": 390, "height": 844}); p2 = ctx2.new_page(); p2.route(re.compile(r"fonts\."), lambda r: r.abort())
    p2.goto(BASE); p2.wait_for_selector(".auth"); p2.fill("#em", "mood@test.ru"); p2.fill("#pw", "secret12"); p2.click('.auth [type="submit"]'); p2.wait_for_selector("#tabbar button", timeout=10000)
    p2.goto(BASE + "#mood-decor"); p2.wait_for_timeout(1500)
    check(p2.locator(".mbph img").count() == 2, "на другом устройстве фото подгружаются")
    ctx2.close()

    print("\n== Расписание ==")
    pg.goto(BASE + "#schedule"); pg.wait_for_timeout(400)
    pg.click('[data-act="schedTpl"]'); pg.wait_for_timeout(800); synced()
    n = S("S.schedule.length"); check(n == 14, f"типовой тайминг: {n} пунктов")
    pg.click(".fab"); sheet().locator('[name="time"]').fill("1945"); sheet().locator('[name="title"]').fill("Сюрприз от друзей"); sheet().locator('[name="who"]').fill("Ведущий"); sheet().locator("[data-save]").click(); pg.wait_for_timeout(300)
    order = S("schedSorted().map(x => x.time + ' ' + x.title)")
    i = order.index("19:45 Сюрприз от друзей")
    check(order[i - 1].startswith("19:00") and order[i + 1].startswith("20:30"), "время «1945» → 19:45, пункт встал на своё место")
    pg.locator("[data-sch]").filter(has_text="Торт").click(); sheet().locator('[name="time"]').fill("21:15"); sheet().locator("[data-save]").click(); pg.wait_for_timeout(300)
    check(S("S.schedule.find(x=>x.title==='Торт').time") == "21:15", "редактирование времени")
    pg.locator("[data-sch]").first.click(); sheet().locator('[name="time"]').fill("25 часов"); sheet().locator("[data-save]").click(); pg.wait_for_timeout(200)
    check(pg.locator(".sheet").count() == 1, "неверное время не сохраняется")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(100)
    sid = S("S.schedule.find(x=>x.title==='Сборы жениха').id")
    sw = pg.locator(f'.sw[data-sw="schedule:{sid}"] .swc'); sw.scroll_into_view_if_needed(); bb = sw.bounding_box(); y = bb["y"] + bb["height"] / 2
    pg.mouse.move(bb["x"] + bb["width"] - 30, y); pg.mouse.down()
    for k in range(1, 11): pg.mouse.move(bb["x"] + bb["width"] - 30 - 15 * k, y)
    pg.mouse.up(); pg.wait_for_timeout(300)
    pg.locator(f'.sw[data-sw="schedule:{sid}"] [data-swdel]').click(); pg.locator(".modal [data-y]").click(); pg.wait_for_timeout(300)
    check(S("S.schedule.length") == 14, "удаление пункта свайпом")
    pg.click('[data-act="schedCopy"]'); pg.wait_for_timeout(300)
    t = clip(); check(t.startswith("Тайминг свадьбы Женя и Катя") and "19:45  Сюрприз от друзей — Ведущий" in t, "«Скопировать тайминг» для координатора")
    pg.screenshot(path=str(SHOTS / "03_schedule.png"), full_page=True)
    with pg.expect_download() as dl: pg.evaluate("() => exportXlsx()")
    wb = openpyxl.load_workbook(io.BytesIO(pathlib.Path(dl.value.path()).read_bytes()))
    check("Тайминг" in wb.sheetnames and wb["Тайминг"].max_row == 15, "тайминг в Excel")
    # backup roundtrip includes mood comments & schedule
    with pg.expect_download() as dl: pg.evaluate("() => backupJSON()")
    import json; bk = json.loads(pathlib.Path(dl.value.path()).read_text())
    check(len(bk["schedule"]) == 14 and len(bk["mbcomments"]) == 3, "расписание и комментарии попадают в резервную копию")
    # desktop
    pg.set_viewport_size({"width": 1440, "height": 900}); pg.goto(BASE + "#mood-decor"); pg.wait_for_timeout(800)
    check(pg.locator('#tabbar [data-go="mood"].on').count() == 1, "десктоп: «Атмосфера» в боковом меню подсвечена")
    pg.screenshot(path=str(SHOTS / "04_desktop_board.png"), full_page=True)
    pg.goto(BASE + "#schedule"); pg.wait_for_timeout(400); pg.screenshot(path=str(SHOTS / "05_desktop_schedule.png"), full_page=True)
    over = S("document.documentElement.scrollWidth - window.innerWidth"); check(over <= 0, "без горизонтальной прокрутки")
    b.close()

print("\nОШИБКИ:" if errors else "\nВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
for e in errors: print(" -", e)
sys.exit(1 if errors else 0)
